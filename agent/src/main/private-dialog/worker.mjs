// A private UI-only worker. The Agent owns storage/authentication and acknowledges each submission.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { randomBytes } from 'node:crypto';
import { app, BrowserWindow, ipcMain, session, screen } from 'electron';
import { SCHEMA, FRAME_LIMIT, DIALOG_TIMEOUT_MS, APPROVE_DELAY_MS, ERROR_TEXT, validateModel, validateSubmission, validateDecision } from './contract.mjs';
export const PRIVATE_DIALOG_FLAG = '--ssam-private-dialog-worker';
export const isPrivateDialogWorker = (argv = process.argv) => argv.includes(PRIVATE_DIALOG_FLAG);

export async function runPrivateDialogWorker() {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'ssam-private-dialog-'));
  try { fs.chmodSync(temp, 0o700); } catch { /* Windows uses the current user's temp ACL. */ }
  app.setPath('userData', path.join(temp, 'user'));
  app.setPath('sessionData', path.join(temp, 'session'));
  app.setPath('crashDumps', path.join(temp, 'crash'));
  app.setAppLogsPath(path.join(temp, 'logs'));
  app.on('window-all-closed', () => {});
  let model, win, pending = false, closing = false, visibleAt = 0, buffer = Buffer.alloc(0), timer;
  let resolveModel;
  const first = new Promise(resolve => { resolveModel = resolve; });
  const input = fs.createReadStream(null, { fd: 0, autoClose: false });
  const emit = value => new Promise(resolve => { const line = JSON.stringify(value) + '\n'; if (Buffer.byteLength(line) > FRAME_LIMIT) { resolve(false); return; } process.stdout.write(line, () => resolve(true)); });
  async function close(accepted, reason) {
    if (closing) return;
    closing = true; clearTimeout(timer); input.destroy(); buffer.fill(0); buffer = Buffer.alloc(0);
    if (win && !win.isDestroyed()) win.destroy();
    await emit({ type: 'closed', id: model?.id ?? null, accepted, ...(reason ? { reason } : {}) });
    // This directory was generated by this worker; renderer data uses an in-memory partition.
    try { fs.rmSync(temp, { recursive: true, force: true }); } catch { /* OS cleanup may finish later. */ }
    // A valid user decline is a completed interaction, not a transport failure.
    app.exit(accepted || (model && reason === 'cancelled') ? 0 : 1);
  }
  process.stdout.on('error', () => { if (!closing) void close(false, 'parent-disconnected'); });
  timer = setTimeout(() => void close(false, 'timeout'), DIALOG_TIMEOUT_MS);
  input.on('data', chunk => {
    if (closing) return;
    buffer = Buffer.concat([buffer, chunk]);
    for (;;) {
      const at = buffer.indexOf(10);
      if (at < 0) { if (buffer.length > FRAME_LIMIT) void close(false, 'invalid'); return; }
      if (at > FRAME_LIMIT) { void close(false, 'invalid'); return; }
      const line = buffer.subarray(0, at); buffer = buffer.subarray(at + 1);
      try {
        const value = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(line));
        if (!model) { model = validateModel(value); resolveModel(model); }
        else {
          const decision = validateDecision(model, value);
          if (!pending) throw new Error('PRIVATE_DIALOG_INVALID_INPUT');
          pending = false;
          if (decision.ok) void close(true);
          else win.webContents.send('private-dialog:state', { busy: false, error: ERROR_TEXT[decision.code] });
        }
      } catch { void close(false, 'invalid'); return; }
    }
  });
  input.on('end', () => { if (!closing) void close(false, 'parent-disconnected'); });
  input.on('error', () => { if (!closing) void close(false, 'parent-disconnected'); });
  await first;
  await app.whenReady();
  if (closing) return;
  const here = path.dirname(fileURLToPath(import.meta.url));
  // electron-vite bundles this worker into out/main/index.js.
  const renderer = path.resolve(here, '../renderer/private-dialog/index.html');
  const rendererRoot = pathToFileURL(path.resolve(here, '../renderer') + path.sep).href;
  const expected = pathToFileURL(renderer).href;
  const ses = session.fromPartition('ssam-private-' + randomBytes(16).toString('hex'), { cache: false });
  ses.webRequest.onBeforeRequest((details, callback) => { let allowed = false; try { const url = new URL(details.url); const relative = path.relative(path.resolve(here, '../renderer'), fileURLToPath(url)); allowed = url.protocol === 'file:' && relative !== '' && !relative.startsWith('..') && !path.isAbsolute(relative); } catch {} callback({ cancel: !allowed }); });
  ses.setPermissionRequestHandler((_contents, _permission, callback) => callback(false));
  ses.setPermissionCheckHandler(() => false);
  ses.on('will-download', (event, item) => { event.preventDefault(); item.cancel(); });
  win = new BrowserWindow({ width: model.form === 'approve' ? 540 : 440, height: 650, useContentSize: true, minWidth: 380, minHeight: 360, show: false,
    title: 'SSAM Agent', autoHideMenuBar: true, backgroundColor: '#fafafa', resizable: true,
    webPreferences: { preload: path.resolve(here, '../preload/private-dialog.cjs'), session: ses,
      sandbox: true, contextIsolation: true, nodeIntegration: false, nodeIntegrationInSubFrames: false, nodeIntegrationInWorker: false,
      webSecurity: true, allowRunningInsecureContent: false, webviewTag: false, devTools: false, spellcheck: false,
      navigateOnDragDrop: false, disableDialogs: true } });
  win.setMenu(null);
  try { win.setContentProtection(true); } catch { /* Not a substitute for the private IPC boundary. */ }
  win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }));
  win.webContents.on('will-navigate', (event, url) => { if (url !== expected) event.preventDefault(); });
  win.webContents.on('will-redirect', event => event.preventDefault());
  win.webContents.on('will-attach-webview', event => event.preventDefault());
  win.webContents.on('context-menu', event => event.preventDefault());
  win.webContents.on('render-process-gone', () => void close(false, 'renderer-closed'));
  win.on('closed', () => { if (!closing) void close(false, 'cancelled'); });
  const own = event => !closing && event.sender === win.webContents && event.senderFrame === win.webContents.mainFrame && event.senderFrame.url === expected;
  ipcMain.handle('private-dialog:bootstrap', event => { if (!own(event)) return null; return { ...model, approveDelayMs: APPROVE_DELAY_MS }; });
  ipcMain.handle('private-dialog:resize', (event, height) => { if (own(event) && Number.isFinite(height) && height >= 200 && height <= 100000) { const max = screen.getDisplayMatching(win.getBounds()).workArea.height - 100; win.setContentSize(win.getContentSize()[0], Math.max(300, Math.min(Math.ceil(height), max))); } return null; });
  ipcMain.handle('private-dialog:cancel', event => { if (own(event)) void close(false, 'cancelled'); return null; });
  ipcMain.handle('private-dialog:submit', async (event, values) => {
    if (!own(event) || pending || !visibleAt) return { ok: false, error: 'The private window is not ready.' };
    if (model.form === 'approve' && Date.now() - visibleAt < APPROVE_DELAY_MS) return { ok: false, error: 'Please review the change before approving.' };
    try { validateSubmission(model, values); }
    catch (error) { return { ok: false, error: ERROR_TEXT[error.message] ?? ERROR_TEXT.PRIVATE_DIALOG_INVALID_INPUT }; }
    pending = true;
    await emit({ type: 'submit', id: model.id, values });
    return { ok: true };
  });
  win.once('ready-to-show', () => { if (closing) return; win.show(); win.focus(); setImmediate(() => { if (closing) return; if (!win.isVisible()) win.show(); if (!win.isVisible()) { void close(false, 'not-visible'); return; } visibleAt = Date.now(); void emit({ type: 'visible', id: model.id }); }); });
  try { await win.loadFile(renderer); } catch { void close(false, 'renderer-closed'); }
}
