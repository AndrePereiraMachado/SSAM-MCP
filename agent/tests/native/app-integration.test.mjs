import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createSupervisor } from '../../src/main/core/supervisor.mjs';
import { stageNativePack } from '../../scripts/native-pack.mjs';
import { fakeHub } from '../../agent/tests/fixtures/fake-hub.mjs';

test('Electron supervisor runs the actual native core, reuses data, relays O11 and leaves sources out of data', { skip: !process.env.SSAM_NATIVE_EXE, timeout: 30000 }, async t => {
  const staging = process.platform === 'darwin' ? path.join(os.homedir(), '.ssam-native-tests') : fileURLToPath(new URL('../../.local/native/', import.meta.url));
  fs.mkdirSync(staging, { recursive: true });
  const parent = fs.mkdtempSync(path.join(staging, 'app-test-'));
  const source = path.join(parent, 'source'), runtime = path.join(parent, 'installed'), root = path.join(parent, 'data');
  fs.mkdirSync(source);
  const script = Buffer.from('throw new Error("legacy source must never execute")');
  fs.writeFileSync(path.join(source, 'legacy.mjs'), script);
  fs.writeFileSync(path.join(source, 'pack.json'), JSON.stringify({ id: 'local-test', platform: process.platform === 'darwin' ? 'darwin' : 'windows', lanes: [], files: [{ path: 'legacy.mjs', size: script.length, sha256: createHash('sha256').update(script).digest('hex') }] }));
  stageNativePack(source, process.env.SSAM_NATIVE_EXE, runtime);
  // Only the synthetic bridge lane is enabled after staging; no installed Studio is changed.
  const manifest = JSON.parse(fs.readFileSync(path.join(runtime, 'pack.json'))); manifest.lanes = ['o11'];
  fs.writeFileSync(path.join(runtime, 'pack.json'), JSON.stringify(manifest));
  const credential = 'ssam_agent_' + 'a'.repeat(43);
  const hub = await fakeHub({ credential });
  const bridgeRequests = [];
  const bridge = net.createServer(socket => {
    let line = ''; socket.on('data', chunk => { line += chunk; if (!line.includes('\n')) return;
      bridgeRequests.push(JSON.parse(line)); socket.end(JSON.stringify({ success: true, data: { path: path.join(root, 'o11/result.oml') } }) + '\n');
    });
  });
  await new Promise(resolve => bridge.listen(0, '127.0.0.1', resolve));
  const supervisor = createSupervisor({ root, packDir: runtime, installedPack: true, fork: () => { throw new Error('Node core must not run'); }, importAgent: () => { throw new Error('Agent sources must not be imported'); } });
  t.after(async () => { await supervisor.shutdown(); await hub.close(); await new Promise(resolve => bridge.close(resolve)); fs.rmSync(parent, { recursive: true, force: true }); });
  supervisor.syncPack();
  const setup = await supervisor.setup({ server: hub.url, credential });
  assert.equal(setup.ok, true, setup.error);
  fs.writeFileSync(path.join(root, 'inbox/retained.txt'), 'retained user data');
  fs.mkdirSync(path.join(root, 'private/authority'));
  fs.writeFileSync(path.join(root, 'private/authority/bridge.key'), 'local-test-key');
  fs.writeFileSync(path.join(root, 'private/o11-connection.json'), JSON.stringify({ pid: 999999, port: bridge.address().port }));
  assert.equal((await supervisor.start()).connected, true);
  assert.equal(hub.hellos[0].agent.runtime, 'native-aot');
  assert.equal(hub.hellos[0].agent.kinds.length, 11);
  hub.stream.write(JSON.stringify({ t: 'call', id: 'invalid-probe', kind: 'net.probe', params: { probes: [{ bytes: 999999999, count: 1 }] } }) + '\n');
  await hub.until(() => hub.results('invalid-probe').length > 0);
  assert.equal(hub.results('invalid-probe')[0].error.code, 'PARAMS_INVALID');
  hub.stream.write(JSON.stringify({ t: 'call', id: 'probe', kind: 'net.probe', params: { probes: [{ bytes: 128, count: 2 }], budgetMs: 500 } }) + '\n');
  await hub.until(() => hub.results('probe').length > 0);
  assert.equal(hub.results('probe')[0].ok, true);
  assert.equal(hub.results('probe')[0].value.probes.length, 2);
  hub.stream.write(JSON.stringify({ t: 'call', id: 'relay', kind: 'o11.bridge', params: { method: 'snapshot_module', params: { path: 'agent:o11/snapshot.oml' }, port: 1, authorization: 'ignored' } }) + '\n');
  await hub.until(() => hub.results('relay').length > 0);
  assert.equal(hub.results('relay')[0].ok, true);
  assert.deepEqual(bridgeRequests[0], { method: 'snapshot_module', params: { path: path.join(root, 'o11/snapshot.oml') }, authorization: 'local-test-key' });
  assert.deepEqual(hub.results('relay')[0].value.paths, [['data', 'path']]);
  assert.equal(hub.results('relay')[0].value.reply.data.path, 'agent:o11/result.oml');
  const report = await supervisor.doctor(); assert.equal(report.ok, true); assert.equal(report.report.runtime, 'native-aot');
  assert.equal((await supervisor.stop()).stopped, true);
  assert.equal(hub.deletes, 1);
  assert.equal(fs.readFileSync(path.join(root, 'inbox/retained.txt'), 'utf8'), 'retained user data');
  assert.deepEqual(fs.readdirSync(root).sort(), ['inbox', 'o11', 'odc', 'private']);
  assert.deepEqual(fs.readdirSync(runtime).sort(), ['native', 'pack.json']);
  assert.equal((await supervisor.start()).connected, true);
  await supervisor.stop();
  const before = fs.readFileSync(path.join(root, 'private/credential'), 'utf8');
  assert.equal((await supervisor.setup({ server: hub.url, credential: 'invalid' })).ok, false);
  assert.equal(fs.readFileSync(path.join(root, 'private/credential'), 'utf8'), before);
});
