test('r41: every backend gets the same workspace quota and retention variables and no core files; the console reads the same quota',()=>{
 const c=generateCompose({...manifest,window:3});
 const backends=Object.entries(c.services).filter(([name])=>/^ssam-server-v\d+$/.test(name)).map(([,s])=>s);
 assert.equal(backends.length,2);
 for(const s of backends){
  assert.equal(s.environment.SSAM_WORKSPACE_QUOTA_GIB,'${SSAM_WORKSPACE_QUOTA_GIB:-10}');
  assert.equal(s.environment.SSAM_WORKSPACE_SCRATCH_DAYS,'${SSAM_WORKSPACE_SCRATCH_DAYS:-3}');
  assert.equal(s.environment.SSAM_WORKSPACE_KEEP_CAPTURES,'${SSAM_WORKSPACE_KEEP_CAPTURES:-3}');
  assert.deepEqual(s.ulimits,{core:0});
 }
 assert.equal(c.services['ssam-console'].environment.SSAM_WORKSPACE_QUOTA_GIB,'${SSAM_WORKSPACE_QUOTA_GIB:-10}');
 assert.deepEqual(c.services['ssam-router'].ulimits,{core:0});
});
