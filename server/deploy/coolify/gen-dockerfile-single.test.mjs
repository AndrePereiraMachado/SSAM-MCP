// The Dockerfile of a correction image (deploy/gen-dockerfile.mjs generateSingleDockerfile, --single; trilha D, the X1
// window): the source commit's own Dockerfile, the pair image layout kept, only the two Studio stages copied from the
// production pair image by digest. Applied to this checkout's server/Dockerfile and to the Dockerfiles of the production
// commits 60e13ec (v1-v4) and dfb584d (v5) when this clone has them.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {generateSingleDockerfile,generateDockerfile,studioTrust} from '../gen-dockerfile.mjs';

const server=fileURLToPath(new URL('../../',import.meta.url));
const count=(text,needle)=>text.split(needle).length-1;
const img='docker.io/andrepereiramachado/ssam-server',ref=c=>img+'@sha256:'+c.repeat(64);
const pin=(version,c)=>({version,tag:'prod-test',image:img,sha256:c.repeat(64)});
// One pair image in both lanes, as versions.json lists the pairs.
const versions={odc:[pin('1.7.28','a'),pin('1.7.32','b')],o11:[pin('11.55.92','a'),pin('11.55.95','b')]};
const trust=studioTrust(versions);
const old={o11:[{version:'11.55.92',fromImage:ref('a'),tfm:'net8.0'}],odc:{version:'1.7.28',fromImage:ref('a'),tfm:'net8.0'}};
const v5={o11:[{version:'11.55.95',fromImage:ref('b')}],odc:{version:'1.7.32',fromImage:ref('b')}};
const bases=[['this checkout',fs.readFileSync(path.join(server,'Dockerfile'),'utf8')]];
for(const c of ['60e13ec','dfb584d']){const r=spawnSync('git',['-C',server,'show',c+':server/Dockerfile'],{encoding:'utf8'});if(r.status===0)bases.push([c,r.stdout]);}

for(const [name,base] of bases)test(`--single on the Dockerfile of ${name}: the pair layout kept, both Studios from their image, nothing else moved`,()=>{
 const out=generateSingleDockerfile(base,old,{trust}),plain=base.replace(/\r\n/g,'\n');
 assert.match(out.split('\n')[1],/^# GENERATED by deploy\/gen-dockerfile\.mjs --single .*o11 11\.55\.92, odc 1\.7\.28\. Do not edit/);
 for(const [lane,stage,dir] of [['o11','studio-o11','/studio/o11'],['odc','studio-odc','/studio/odc']]){
  assert.equal(count(out,`FROM ${ref('a')} AS studio-image-${lane}\n`),1,lane+': the image by digest');
  assert.equal(count(out,`FROM studio-image-reader AS ${stage}\n`),1,lane+': the stage keeps its name');
  assert.equal(count(out,`sh studio-from-image.sh ${lane} /from-image studio-${lane}.txt ${dir} `),1,lane+': copied to the production folder');
  assert.equal(count(out,`COPY --from=${stage} /studio-from-image/ /app/studio-from-image/\n`),1,lane+': its sha256 list');
  assert.equal(count(out,`ssam.studio.${lane}.${lane==='o11'?'11.55.92':'1.7.28'}.source="image ${ref('a')}" \\\n`),1,lane+': its source label');
 }
 assert.equal(count(out,'FROM studio-reader AS studio-image-reader\n'),1);
 assert.equal(count(out,'require-pinned.sh'),count(plain,'require-pinned.sh')-2,'the two bundle pins are gone, the reader keeps its own');
 for(const v of ['ARG SSAM_IMAGE_O11=11.55.92\n','ARG SSAM_IMAGE_ODC=1.7.28\n','ARG SERVICE_STUDIO_TFM=net8.0\n','ARG ODC_STUDIO_TFM=net8.0\n'])assert.equal(count(out,v),1,v.trim());
 // The production layout: one Studio folder, one kernel, the ENV and the checks of the base, unchanged.
 for(const kept of ['COPY --from=studio-o11 /studio/o11 /studio/o11\n','COPY --from=kernel-o11 /out/ /app/\n','    ANVIL_STUDIO_DIR=/studio/o11 \\\n',
  '-p:SSDir=/studio/o11 ','RUN node /app/platforms/odc/facade/kernel-image.mjs check-image "/studio/o11=${SSAM_IMAGE_O11}" "/studio/odc=${SSAM_IMAGE_ODC}"\n','FROM sdk AS kernel-o11\n'])
  assert.equal(count(out,kept),count(plain,kept),'kept: '+kept.trim());
 assert.equal(count(out,'/studio/o11/11.55.92'),0,'no multi-O11 folder');
 assert.equal(count(out,'SSAM_O11_STUDIO_ROOT'),count(plain,'SSAM_O11_STUDIO_ROOT'),'no new ENV');
 // Every line of the runtime stage after the Studio copies is the base's, but the provenance copies and the labels.
 const tail=t=>t.slice(t.indexOf('# ---- JavaScript dependencies ')).split('\n').filter(l=>!l.includes('studio-from-image')&&!l.includes('ssam.studio.'));
 assert.deepEqual(tail(out),tail(plain),'nothing after the Studio stages moved');
 const five=generateSingleDockerfile(base,v5,{trust});
 assert.equal(count(five,'ARG SERVICE_STUDIO_TFM=\n'),1,'11.55.95 has no tfm pin');assert.equal(count(five,'ARG SSAM_IMAGE_O11=11.55.95\n'),1);
});

test('--single refuses what is not a correction image: two O11, a bundle, no ODC image, an image outside versions.json, the multi-O11 base',()=>{
 const base=fs.readFileSync(path.join(server,'Dockerfile'),'utf8');
 assert.throws(()=>generateSingleDockerfile(base,{...old,o11:[...old.o11,{version:'11.55.95',fromImage:ref('b')}]},{trust}),/one Service Studio/);
 assert.throws(()=>generateSingleDockerfile(base,{...old,o11:[{version:'11.55.92',bundle:'o11-studio-11.55.92.1.tar.gz',sha256:'c'.repeat(64)}]},{trust}),/both Studios from images/);
 assert.throws(()=>generateSingleDockerfile(base,{o11:old.o11},{trust}),/both Studios from images/);
 assert.throws(()=>generateSingleDockerfile(base,{...old,odc:{version:'1.7.28',fromImage:ref('d')}},{trust}),/not in the trust list/);
 assert.throws(()=>generateSingleDockerfile(base,old,{trust:null}),/trust list/);
 const multi=generateDockerfile(base,{o11:[{version:'11.55.92',fromImage:ref('a'),tfm:'net8.0'}],odc:old.odc},{trust});
 assert.throws(()=>generateSingleDockerfile(multi,old,{trust}),/anchor|layout/,'a generated multi-O11 file is no base');
});
