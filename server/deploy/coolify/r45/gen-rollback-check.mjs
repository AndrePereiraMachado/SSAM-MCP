// after a rollback and its Redeploy, every backend and the router must run the r44 image with the r44 limits (the unsized
// compose: cpus/memory from SSAM_CPUS/SSAM_MEMORY, whose Coolify values today give 2 CPU and 6g), CpuShares 0 (weight 100),
// no tier label, and the stored compose must be the r44 one. Last line: ROLLBACK OK or ROLLBACK FAIL <n>.
import fs from 'node:fs';import cp from 'node:child_process';
const git=process.env.R45_GIT??'C:/Program Files/Git/cmd/git.exe',wt=process.env.R45_REPO??'C:/t/r5/wt-capacity',U='ksqommjgowjjilpgpbmf7cdo';
const c=JSON.parse(cp.execFileSync(git,['-C',wt,'show','fb3be56:server/deploy/coolify/compose.coolify.yml'],{encoding:'utf8'}).replace(/^#.*\n/,''));
// The running r44 limits read on the VPS on 2026-11-09 (docker inspect): NanoCpus 2e9, Memory 6 GiB on every backend and the router.
const NANO=2000000000,MEM=6442450944;
let sh=`#!/bin/bash
# rollback-check.sh (r45 capacity, generated by deploy-r45/gen-rollback-check.mjs from fb3be56). READ-ONLY.
fail=0
chk() { if [ "$2" = "$3" ]; then echo "ok   $1 $4=$2"; else echo "FAIL $1 $4: running $2, expected $3"; fail=$((fail+1)); fi; }
`;
for(const [svc,s] of Object.entries(c.services)){
 if(!/^ssam-(server-v\d|router|console)$/.test(svc))continue;
 sh+=`c=${svc}-${U}
if docker inspect "$c" >/dev/null 2>&1; then
chk ${svc} "$(docker inspect -f '{{.Config.Image}}' "$c")" '${s.image}' image
`;
 if(svc!=='ssam-console')sh+=`read nano mem shares <<<"$(docker inspect -f '{{.HostConfig.NanoCpus}} {{.HostConfig.Memory}} {{.HostConfig.CpuShares}}' "$c")"
chk ${svc} "$nano" ${NANO} NanoCpus; chk ${svc} "$mem" ${MEM} Memory; chk ${svc} "$shares" 0 CpuShares
chk ${svc} "$(docker exec "$c" cat /sys/fs/cgroup/cpu.weight 2>/dev/null)" 100 cpu.weight
chk ${svc} "$(docker inspect -f '{{index .Config.Labels "ssam.sizing"}}' "$c")" '' tier-label
`;
 sh+=`else echo "FAIL ${svc}: no container"; fail=$((fail+1)); fi
`;
}
sh+=`[ "$fail" = 0 ] && echo "ROLLBACK OK" || echo "ROLLBACK FAIL $fail"
`;
fs.writeFileSync(new URL('./rollback-check.sh',import.meta.url),sh);
console.log('rollback-check.sh written');
