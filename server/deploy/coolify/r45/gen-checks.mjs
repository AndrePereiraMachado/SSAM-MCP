// node gen-checks.mjs --option a|c --pin <rev> --out <dir> [--c6-file <compose>] [--since <YYYY-MM-DD>] (normally run by kit.mjs)
// Builds <out>/env-check.sh (READ-ONLY, run on the VPS after the Redeploy by r45-window.sh, or by hand:
// `ssh ... 'bash -s' < env-check.sh`) from sizedExpectations(versions.json of the pin) and the pin's compose. For each backend
// and the router it compares the running container's NanoCpus, Memory, memory.max, CpuShares and cgroup cpu.weight (the
// weight runc 1.5.1 writes, gen-compose cpuWeight: review R3 A1), the three pool variables (match/mismatch only, never a
// value) and the tier label; for EVERY service of the compose the running image (option (a) moves them all to the r45
// images, option (c) keeps the r44 ones); and it lists the keys (never values) of Coolify resource variables named
// SSAM_HOT_*, SSAM_OTHER_*, SSAM_ROUTER_* or created on or after --since (the release day). The last line is ENVCHECK OK or
// ENVCHECK FAIL <n>: any FAIL is the abort criterion (rollback).
import fs from 'node:fs';import cp from 'node:child_process';
const git=process.env.R45_GIT??'C:/Program Files/Git/cmd/git.exe',wt=process.env.R45_REPO??'C:/t/r5/wt-capacity';
const argv=process.argv.slice(2),opt=k=>{const i=argv.indexOf(k);return i>=0?argv[i+1]:undefined;};
const OPTION=opt('--option');if(!['a','c'].includes(OPTION))throw new Error('--option a|c');
const pinArg=opt('--pin')??'HEAD',since=opt('--since')??new Date().toISOString().slice(0,10),c6File=opt('--c6-file');
const out=opt('--out');if(!out)throw new Error('--out <dir>');
const pin=cp.execFileSync(git,['-C',wt,'rev-parse','--short',pinArg],{encoding:'utf8'}).trim();
if(!/^\d{4}-\d{2}-\d{2}$/.test(since))throw new Error('--since YYYY-MM-DD');
const show=f=>cp.execFileSync(git,['-C',wt,'show',`${pin}:server/deploy/coolify/${f}`],{encoding:'utf8'});
// gen-compose.mjs and its template of the pin (not the working tree), imported from a private copy.
const tmp=fs.mkdtempSync(`${out}/.pin-`);
for(const f of ['gen-compose.mjs','compose.template.json'])fs.writeFileSync(`${tmp}/${f}`,show(f));
let exp,cpuWeight,compose;
try{const m=await import('file:///'+tmp.replace(/\\/g,'/')+'/gen-compose.mjs');cpuWeight=m.cpuWeight;
 if(c6File){compose=JSON.parse(fs.readFileSync(c6File,'utf8').replace(/^#.*\n/,''));const v=JSON.parse(fs.readFileSync(c6File.replace(/compose\.coolify\.yml$/,'versions.json'),'utf8'));exp=m.sizedExpectations(v);}
 else{compose=JSON.parse(show('compose.coolify.yml').replace(/^#.*\n/,''));exp=m.sizedExpectations(JSON.parse(show('versions.json')));}
}finally{fs.rmSync(tmp,{recursive:true,force:true});}
if(!exp)throw new Error('versions.json of the pin has no sizing');
const U='ksqommjgowjjilpgpbmf7cdo';
let sh=`#!/bin/bash
# env-check.sh (r45 capacity, option (${OPTION}), generated by deploy-r45/gen-checks.mjs from ${c6File?'a rehearsal file':pin}). READ-ONLY:
# docker inspect, cat of cgroup files, one SELECT of keys. Prints limits (numbers), images and match/mismatch for the pools;
# never an environment value.
fail=0
chk() { if [ "$2" = "$3" ]; then echo "ok   $1 $4=$2"; else echo "FAIL $1 $4: running $2, expected $3"; fail=$((fail+1)); fi; }
`;
for(const [svc,e] of Object.entries(exp)){
 const c=`${svc}-${U}`;
 sh+=`c=${c}
if ! docker inspect "$c" >/dev/null 2>&1; then echo "FAIL ${svc}: no container"; fail=$((fail+1)); else
read nano mem shares <<<"$(docker inspect -f '{{.HostConfig.NanoCpus}} {{.HostConfig.Memory}} {{.HostConfig.CpuShares}}' "$c")"
chk ${svc} "$nano" ${e.NanoCpus} NanoCpus; chk ${svc} "$mem" ${e.Memory} Memory
chk ${svc} "$(docker exec "$c" cat /sys/fs/cgroup/memory.max 2>/dev/null)" ${e.Memory} memory.max
chk ${svc} "$shares" ${e.CpuShares??0} CpuShares; chk ${svc} "$(docker exec "$c" cat /sys/fs/cgroup/cpu.weight 2>/dev/null)" ${cpuWeight(e.CpuShares??0)} cpu.weight
`;
 if(e.env){
  sh+=`envs="$(docker inspect -f '{{range .Config.Env}}{{println .}}{{end}}' "$c")"
`;
  for(const [k,v] of Object.entries(e.env))sh+=`if grep -qx '${k}=${v}' <<<"$envs"; then echo "ok   ${svc} ${k} matches"; else echo "FAIL ${svc} ${k} mismatch"; fail=$((fail+1)); fi
`;
  sh+=`[ "$(docker inspect -f '{{index .Config.Labels "ssam.sizing"}}' "$c")" = "${e.tier}" ] && echo "ok   ${svc} tier ${e.tier} (${e.pair})" || { echo "FAIL ${svc} tier label"; fail=$((fail+1)); }
`;
 }
 sh+=`fi
`;
}
// The image of every service of the compose (Coolify keeps the tag; the digest is the backend's ssam.image.digest label).
for(const [svc,s] of Object.entries(compose.services)){
 const digest=s.labels?.['ssam.image.digest'];
 sh+=`c=${svc}-${U}
if docker inspect "$c" >/dev/null 2>&1; then chk ${svc} "$(docker inspect -f '{{.Config.Image}}' "$c")" '${s.image}' image
${digest?`  chk ${svc} "$(docker image inspect -f '{{join .RepoDigests " "}}' "$(docker inspect -f '{{.Image}}' "$c")" | tr ' ' '\\n' | grep -c '@${digest}$')" 1 digest
`:''}else echo "skip ${svc}: no running container (not part of this check)"; fi
`;
}
sh+=`echo '--- Coolify resource variables (keys only): tier names, or created on/after ${since}'
keys="$(docker exec -i coolify-db psql -U coolify -d coolify -tA <<'SQL'
select v.key from environment_variables v join services s on s.id = v.resourceable_id
where v.resourceable_type like '%Service' and s.uuid = '${U}'
  and (v.key ~ '^SSAM_(HOT|OTHER|ROUTER)_' or v.created_at >= '${since}')
order by v.key;
SQL
)" || keys="(the SELECT failed)"
if [ -n "$keys" ]; then echo "FAIL new or tier variables: $(echo $keys)"; fail=$((fail+1)); else echo "ok   no new Coolify variable"; fi
[ "$fail" = 0 ] && echo "ENVCHECK OK" || echo "ENVCHECK FAIL $fail"
`;
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(`${out}/env-check.sh`,sh.replace(/\r/g,''));
console.log(JSON.stringify({option:OPTION,pin:c6File?'file':pin,since,services:Object.keys(exp),images:Object.keys(compose.services).length}));
