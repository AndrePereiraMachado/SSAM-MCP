// Window 4x4, phase S1 (design B: C:/t/r5/janela-4x4/DESENHO.md 1.4 item 1): the multi-O11 Dockerfile generated from the
// production one (deploy/gen-dockerfile.mjs). Applied to the real server/Dockerfile: one pinned studio stage and one kernel
// stage per Service Studio, the runtime layout /studio/o11/<v> and /app/kernel/.local/o11/<v>/cli that o11-kernels.mjs
// reads, the default kernel for the server's own processes, and no single-O11 leftover. A changed anchor stops the generator.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {generateDockerfile,o11KernelList,slugOf} from '../gen-dockerfile.mjs';

const server=fileURLToPath(new URL('../../',import.meta.url));
const base=fs.readFileSync(path.join(server,'Dockerfile'),'utf8');
const sha=c=>c.repeat(64);
const BUILDS={'11.55.92':'65269','11.55.93':'65289','11.55.94':'65328','11.55.95':'65352'};
const spec={default:'11.55.95',o11:Object.entries(BUILDS).reverse().map(([version,build],i)=>({version,bundle:`o11-studio-${version}.${build}.tar.gz`,sha256:sha('abcd'[i]),
 ...(version<'11.55.94'?{tfm:'net8.0'}:{})}))};
const count=(text,needle)=>text.split(needle).length-1;

test('gen-dockerfile: every Service Studio of the window gets a pinned studio stage and its own kernel stage',()=>{
 const out=generateDockerfile(base,spec);
 assert.match(out.split('\n')[1],/^# GENERATED by deploy\/gen-dockerfile\.mjs .*11\.55\.92,11\.55\.93,11\.55\.94,11\.55\.95, default 11\.55\.95/);
 assert.match(out,/^ARG SSAM_IMAGE_O11=11\.55\.92,11\.55\.93,11\.55\.94,11\.55\.95$/m);
 for(const {version,bundle,sha256,tfm} of spec.o11){
  const s=slugOf(version);
  assert.equal(count(out,`FROM studio-reader AS studio-o11-${s}\n`),1,version);
  assert.equal(count(out,`sh require-pinned.sh SERVICE_STUDIO_${s.replaceAll('-','_')} "-" "" "" "${bundle}" "${sha256}"`),1,version+': its bundle pinned by its SHA256');
  assert.ok(out.includes(`studio-extract.sh o11 "-" "" "" ServiceStudio.Framework.dll studio-o11.txt /studio/o11/${version} "${bundle}" "${sha256}"`),version);
  assert.equal(count(out,`FROM sdk AS kernel-o11-${s}\n`),1,version);
  assert.ok(out.includes(`--mount=type=cache,id=ssam-nuget-kernel-o11-${s},`),version+': its own NuGet cache');
  assert.ok(out.includes(`-p:SSDir=/studio/o11/${version}${tfm?' -p:AnvilO11StudioTfm='+tfm:''} -o /out/kernel/.local/o11/${version}/cli`),version);
  assert.equal(count(out,`COPY --from=studio-o11-${s} /studio/o11/${version} /studio/o11/${version}\n`),1,version);
  assert.equal(count(out,`COPY --from=kernel-o11-${s} /out/ /app/\n`),1,version);
  assert.equal(count(out,`/studio/o11/${version}=${version}`),1,version+': check-image');
 }
 assert.ok(out.includes('RUN test "${SSAM_IMAGE_O11}" = "11.55.92,11.55.93,11.55.94,11.55.95"'));
 assert.ok(out.includes('ln -s o11/11.55.95/cli /app/kernel/.local/cli'),'the default CLI for the server\'s own processes');
 assert.ok(out.includes('ANVIL_STUDIO_DIR=/studio/o11/11.55.95 \\\n    SSAM_O11_STUDIO_ROOT=/studio/o11 \\\n    SSAM_O11_CLI_ROOT=/app/kernel/.local/o11 \\\n'));
 assert.ok(out.includes('ssam.kernels.o11.default="11.55.95"'));
 assert.ok(out.includes('from=studio-o11-11-55-95,source=/studio/o11/11.55.95,target=/studio/o11 \\'),'the SkiaSharp probe builds against the default');
 for(const left of ['AS studio-o11\n','AS kernel-o11\n','from=studio-o11,','--from=kernel-o11 ','--from=studio-o11 ','-o /out/kernel/.local/cli '])assert.equal(count(out,left),0,left);
 assert.equal(generateDockerfile(base.replaceAll('\n','\r\n'),spec),out,'CRLF checkouts generate the same file');
 assert.equal(generateDockerfile(base,{...spec,o11:[...spec.o11].reverse()}),out,'the order of the list does not matter');
 assert.equal(generateDockerfile(base,{o11:spec.o11}),out,'the default defaults to the newest');
});

test('gen-dockerfile: nothing unpinned or ambiguous is generated; a changed anchor stops it',()=>{
 const one=spec.o11[0];
 for(const [o11,re] of [
  [[{...one,sha256:''}],/no pinned SHA256/],[[{...one,sha256:sha('A')}],/no pinned SHA256/],
  [[{...one,bundle:'o11-studio.tar.gz'}],/carries the version/],[[{...one,bundle:'../'+one.bundle}],/carries the version/],
  [[one,{...one}],/Duplicate O11 version/],[[{...one,version:'11.55'}],/Invalid O11 version/],
  [[{...one,url:'https://x'}],/unknown fields/],[[{...one,tfm:'net8'}],/Invalid tfm/],[[],/1 to 8 bundles/]])assert.throws(()=>o11KernelList({o11}),re);
 assert.throws(()=>o11KernelList({default:'11.55.91',o11:spec.o11}),/not in the list/);
 assert.deepEqual(o11KernelList(spec).list.map(e=>e.version),Object.keys(BUILDS));
 assert.throws(()=>generateDockerfile(base.replace('COPY --from=kernel-o11 /out/ /app/\n','COPY --from=kernel-o11 /out/ /srv/\n'),spec),/anchor/);
 assert.throws(()=>generateDockerfile(base.replace('    ANVIL_STUDIO_DIR=/studio/o11 \\\n','    ANVIL_STUDIO_DIR=/opt/o11 \\\n'),spec),/anchor/);
});

test('gen-dockerfile: the command writes the generated file and build.sh builds the file SSAM_DOCKERFILE names',()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'gen-dockerfile-'));
 try{
  fs.writeFileSync(path.join(dir,'k.json'),JSON.stringify(spec));
  const out=path.join(dir,'Dockerfile.o11k');
  const run=spawnSync(process.execPath,[path.join(server,'deploy','gen-dockerfile.mjs'),path.join(dir,'k.json'),out],{encoding:'utf8'});
  assert.equal(run.status,0,run.stderr);
  const said=JSON.parse(run.stdout);assert.equal(path.resolve(said.output),path.resolve(out));assert.deepEqual({...said,output:null},{ok:true,output:null,o11:Object.keys(BUILDS),default:'11.55.95'});
  assert.equal(fs.readFileSync(out,'utf8'),generateDockerfile(base,spec));
  // build.sh with a docker mock that records its arguments: -f is the generated file, the context stays server/.
  const slash=p=>p.replaceAll('\\','/'),args=path.join(dir,'args.txt'),mock=path.join(dir,'docker.sh');
  fs.writeFileSync(mock,`#!/bin/sh\ncase "$1 $2" in\n'buildx build') printf '%s\\n' "$@" > '${slash(args)}'; while [ $# -gt 0 ]; do if [ "$1" = --metadata-file ]; then shift; printf '%s' '{"containerimage.digest":"sha256:${'a'.repeat(64)}"}' > "$1"; fi; shift; done;;\n'image inspect') echo 123;;\n*) :;;\nesac\n`);
  const build=spawnSync(process.platform==='win32'?'C:/Program Files/Git/bin/bash.exe':'bash',[slash(path.join(server,'deploy','build.sh')),'--image','ssam-local-test','--tag','candidate-4x4'],
   {encoding:'utf8',env:{...process.env,DOCKER:'sh '+slash(mock),STUDIO_INSTALLERS_DIR:slash(dir),SSAM_ENV_FILE:slash(path.join(dir,'missing.env')),SSAM_BUILD_METADATA_FILE:slash(path.join(dir,'meta.json')),SSAM_DOCKERFILE:slash(out)}});
  assert.equal(build.status,0,build.stderr);
  const recorded=fs.readFileSync(args,'utf8').trim().split('\n');
  assert.equal(slash(recorded[recorded.indexOf('-f')+1]).toLowerCase(),slash(out).toLowerCase());
  assert.equal(recorded.at(-1),'.');
  const missing=spawnSync(process.platform==='win32'?'C:/Program Files/Git/bin/bash.exe':'bash',[slash(path.join(server,'deploy','build.sh')),'--image','ssam-local-test','--tag','candidate-4x4'],
   {encoding:'utf8',env:{...process.env,DOCKER:'sh '+slash(mock),STUDIO_INSTALLERS_DIR:slash(dir),SSAM_ENV_FILE:slash(path.join(dir,'missing.env')),SSAM_DOCKERFILE:'deploy/.generated/none'}});
  assert.equal(missing.status,2);assert.match(missing.stderr,/no Dockerfile/);
 }finally{fs.rmSync(dir,{recursive:true,force:true});}
});
