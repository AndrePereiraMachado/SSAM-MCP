// Capacity sizing (KVM 8, 2026-11-09, C:/t/r5/capacity/RESULTADO.md): the watcher's rotation and its live-compose merge
// move the hot tier to the newest pair, and the previous hot backend steps down to the other tier.
import test from 'node:test';
import assert from 'node:assert/strict';
import {rotateWindow,replayApprovals,pinDigest} from './window.mjs';
import {generateCompose,sizingOfCompose} from '../coolify/gen-compose.mjs';
import {liveBaseline,preserveCompose,parseCompose} from './safety.mjs';
const sha='a'.repeat(64),image='registry/image';
const sizing={hot:{cpus:'4',memory:'12g',buildWorkers:6,o11WorkersMax:4,queueMs:240000},other:{cpus:'1',memory:'2g',buildWorkers:1,o11WorkersMax:1,queueMs:240000},
 router:{cpus:'1',memory:'1g'},host:{memory:'32g',reserve:'4g'}};
const entry=(version,tag)=>({version,tag,image,sha256:sha});
const live3=()=>({window:3,sizing:structuredClone(sizing),odc:[entry('1.7.31','t31'),entry('1.7.30','t30')],o11:[entry('11.55.94','t31'),entry('11.55.94','t30')]});
const tierOf=(c,odc)=>Object.values(c.services).find(s=>s.labels?.['ssam.backend']==='true'&&s.labels['ssam.odc']===odc).labels['ssam.sizing'];
const snapshotOf=manifest=>{
 const compose=generateCompose(manifest);
 const backends=Object.values(compose.services).filter(s=>s.labels?.['ssam.backend']==='true').map(s=>{const kernel={odc:s.labels['ssam.odc'],o11:s.labels['ssam.o11']};return {...kernel,reference:s.image,digest:'sha256:'+sha,kernel};});
 return {compose:'# Generated by gen-compose.mjs.\n'+JSON.stringify(compose,null,2)+'\n',backends};
};
test('rotation carries the sizing and the hot tier follows the new (newest) pair; a hotPair pin is dropped and reported',()=>{
 const before=live3();assert.equal(tierOf(generateCompose(before),'1.7.31'),'hot');
 const r=rotateWindow(before,{odc:'1.7.32',o11:'11.55.95',image,tag:'t32',sha256:sha});
 assert.deepEqual(r.manifest.sizing,sizing);assert.equal(r.hotPinDropped,undefined);
 const c=generateCompose(r.manifest);
 assert.equal(tierOf(c,'1.7.32'),'hot');assert.equal(tierOf(c,'1.7.31'),'other');assert.equal(tierOf(c,'1.7.30'),'other');
 const pinned=rotateWindow({...before,sizing:{...sizing,hotPair:'o11-11.55.94-odc-1.7.30'}},{odc:'1.7.32',o11:'11.55.95',image,tag:'t32',sha256:sha});
 assert.equal(pinned.hotPinDropped,'o11-11.55.94-odc-1.7.30');assert.equal(pinned.manifest.sizing.hotPair,undefined);
 assert.equal(tierOf(generateCompose(pinned.manifest),'1.7.32'),'hot');
 // An unsized window stays unsized (the compose is exactly as before the sizing existed).
 const {sizing:_s,...plain}=before;assert.equal(rotateWindow(plain,{odc:'1.7.32',o11:'11.55.95',image,tag:'t32'}).manifest.sizing,undefined);
 // The pin of the approved digest and the replay of approvals keep it.
 assert.deepEqual(pinDigest(r.manifest,'t32','sha256:'+'b'.repeat(64)).sizing,sizing);
 assert.deepEqual(replayApprovals(before,[{id:'x',pair:{odc:'1.7.32',o11:'11.55.95'},built:{image,tag:'t32'},approved:{at:'2026-11-09T00:00:00Z',digest:'sha256:'+sha}}]).manifest.sizing,sizing);
});
test('the live baseline reads the sizing back, and the live-compose merge resizes retained backends to their new tier',()=>{
 const snapshot=snapshotOf(live3()),baseline=liveBaseline(snapshot);
 assert.deepEqual(baseline.manifest.sizing,sizing);
 const next=rotateWindow(baseline.manifest,{odc:'1.7.32',o11:'11.55.95',image,tag:'t32',sha256:sha}).manifest;
 const merged=parseCompose(preserveCompose(snapshot,next)),want=generateCompose(next);
 for(const [name,s] of Object.entries(merged.services).filter(([,s])=>s.labels?.['ssam.backend']==='true')){
  const w=want.services[name];
  assert.equal(s.labels['ssam.odc'],w.labels['ssam.odc'],name);
  assert.equal(s.labels['ssam.sizing'],w.labels['ssam.sizing'],name);
  assert.deepEqual(s.deploy.resources.limits,w.deploy.resources.limits,name);
  for(const key of ['SSAM_BUILD_WORKERS','SSAM_O11_WORKERS_MAX','SSAM_BUILD_QUEUE_MS'])assert.equal(s.environment[key],w.environment[key],name+' '+key);
 }
 assert.equal(tierOf(merged,'1.7.32'),'hot');assert.equal(tierOf(merged,'1.7.31'),'other');
 assert.deepEqual(sizingOfCompose(merged),sizing);
 assert.deepEqual(merged.services['ssam-router'].deploy.resources.limits,want.services['ssam-router'].deploy.resources.limits);
 // An unreadable sizing label on the live router stops the round before anything is planned.
 const bad=JSON.parse(snapshot.compose.replace(/^#.*\n/,''));bad.services['ssam-router'].labels['ssam.sizing']='{';
 assert.throws(()=>liveBaseline({...snapshot,compose:JSON.stringify(bad)}),e=>e.code==='LIVE_INVALID');
});
test('an unsized live compose keeps every retained backend exactly as it runs',()=>{
 const {sizing:_s,...plain}=live3(),snapshot=snapshotOf(plain),baseline=liveBaseline(snapshot);
 assert.equal(baseline.manifest.sizing,undefined);
 const next=rotateWindow(baseline.manifest,{odc:'1.7.32',o11:'11.55.95',image,tag:'t32',sha256:sha}).manifest;
 const merged=parseCompose(preserveCompose(snapshot,next)),old=parseCompose(snapshot.compose);
 for(const name of ['ssam-server-v1','ssam-server-v2'])assert.deepEqual(merged.services[name].deploy,old.services[name].deploy);
 assert.equal(merged.services['ssam-router'].labels['ssam.sizing'],undefined);
});
