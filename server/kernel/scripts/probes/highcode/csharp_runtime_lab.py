"""Build/run the authenticated C# differential laboratory; no business graph is authored here.

The .cs source and case manifest are generated by RuntimeCaseSourceTests through the public
source compiler. This adapter adds temporary native HTTP test transport and a dedicated
fictional user. It never changes the access contract of an authored business action.
Deliver/publish the generated job separately, only to the authorized personal lab.
"""
from __future__ import annotations
import argparse
import json
import pathlib
import secrets
import shutil
import time
import urllib.error
import urllib.parse
import urllib.request

HOST = "personal-2qqw9srv.outsystemscloud.com"
MODULE = "ZZHighCodeLab_CS"


def literal(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def build(work: pathlib.Path, replace: bool = False) -> None:
    secret_file = work / "secrets.json"
    if not secret_file.exists():
        secret_file.write_text(json.dumps({"key": secrets.token_urlsafe(32),
            "password": secrets.token_urlsafe(32),
            "username": "anvil-lab-" + secrets.token_hex(8) + "@example.invalid"}), encoding="utf-8")
    credentials = json.loads(secret_file.read_text(encoding="utf-8"))
    cases = json.loads((work / "cases.json").read_text(encoding="utf-8"))
    ops: list[dict] = ([{"op": "delete", "target": target} for target in [
        "IRestService:CSharpLab", "IServerAction:LabAuthenticate", "IUserException:LabAccessDenied"]] if replace else [])
    ops.extend([{"op": "reference", "producer": "Users", "elements": [
        "IServerAction:User_Login", "IServerAction:EncryptPassword"]},
        {"op": "create", "parent": "@espace", "type": "IUserException", "name": "LabAccessDenied"}])
    auth = {"name": "LabAuthenticate", "public": False,
        "inputs": [{"name": "LabKey", "type": "Text"}],
        "vars": [{"name": "NewUser", "type": "User"}],
        "steps": [
            {"if": "LabKey <> " + literal(credentials["key"]), "then": [
                {"raise": "LabAccessDenied", "message": literal("Invalid laboratory key.")}]},
            {"get": "User", "as": "LabUser", "where": ["User.Username = " + literal(credentials["username"])], "max": "1"},
            {"if": "LabUser.List.Empty", "then": [
                {"call": "EncryptPassword", "as": "HashPassword", "args": {
                    "Username": literal(credentials["username"]), "Password": literal(credentials["password"])}},
                {"assign": {"NewUser.Username": literal(credentials["username"]),
                    "NewUser.Name": literal("CSharp differential lab"),
                    "NewUser.Password": "HashPassword.EncryptedPassword", "NewUser.Is_Active": "True",
                    "NewUser.Creation_Date": "CurrDateTime()"}},
                {"create": "User", "record": "NewUser", "as": "CreateLabUser"}]},
            {"call": "User_Login", "as": "Authenticate", "args": {
                "Username": literal(credentials["username"]), "Password": literal(credentials["password"]), "RememberLogin": "False"}},
            {"call": "GrantSupervisorRole", "as": "GrantLabRole", "args": {"UserId": "GetUserId()"}}]}
    ops.append({"op": "logic", "data": {"actions": [auth]}})

    def create(parent: str, kind: str, alias: str, name: str | None = None) -> str:
        op = {"op": "create", "parent": parent, "type": kind, "as": alias}
        if name is not None:
            op["name"] = name
        ops.append(op)
        return alias

    def setting(target: str, prop: str, value) -> None:
        ops.append({"op": "set", "target": target, "prop": prop, "value": value})

    def link(start: str, end: str) -> None:
        ops.append({"op": "link", "from": start, "to": end})

    def assignment(parent: str, alias: str, value: str) -> str:
        node = create(parent, "IAssignNode", alias, "SetResult")
        field = create(node, "IAssignment", alias + "Field")
        setting(field, "Variable", "Passed")
        setting(field, "Value", value)
        return node

    service = create("@espace", "IRestService", "$lab", "CSharpLab")
    for case in cases:
        name = case["case"]
        method = create(service, "IRestServiceAction", "$" + name, name)
        setting(method, "HTTPMethod", "POST")
        setting(method, "URLPath", "/" + name)
        key = create(method, "IRestServiceActionInput", method + "Key", "LabKey")
        setting(key, "DataType", "Text")
        setting(key, "ReceiveIn", "Header")
        setting(key, "IsMandatory", True)
        output = create(method, "IRestServiceActionOutput", method + "Output", "Passed")
        setting(output, "DataType", "Boolean")
        setting(output, "SendIn", "Body")
        authenticate = create(method, "IExecuteServerActionNode", method + "Auth", "AuthenticateLab")
        setting(authenticate, "Action", "IServerAction:LabAuthenticate")
        setting(authenticate + "/LabKey", "Value", "LabKey")
        execute = create(method, "IExecuteServerActionNode", method + "Execute", "ExecuteCase")
        setting(execute, "Action", "IServerAction:" + name)
        result = assignment(method, method + "Result", "ExecuteCase.AvResult")
        link(method + "/#IStartNode", authenticate)
        link(authenticate, execute)
        link(execute, result)
        link(result, method + "/#IEndNode")
        if case["expectedException"]:
            handler = create(method, "IExceptionHandlerNode", method + "Catch", "ExpectedException")
            setting(handler, "Exception", "IUserException:" + case["expectedException"])
            setting(handler, "AbortTransaction", False)
            setting(handler, "LogError", False)
            caught = assignment(method, method + "Expected", "True")
            end = create(method, "IEndNode", method + "CaughtEnd")
            link(handler, caught)
            link(caught, end)
        ops.append({"op": "layout", "target": method})
    contract = json.loads((work / "contract.json").read_text(encoding="utf-8"))
    actions = {action["name"]: action for action in contract["logic"]["actions"]}
    if "IsBlank" in actions:
        optional_text = actions["IsBlank"]["inputs"][0]["type"]
        for name in ["IsBlank", "IsEmpty", "Clean", "CleanStart", "CleanEnd", "Echo", "CarriageReturn"]:
            action = actions[name]
            method = create(service, "IRestServiceAction", "$Probe" + name, "Probe" + name)
            setting(method, "HTTPMethod", "POST")
            setting(method, "URLPath", "/Probe" + name)
            key = create(method, "IRestServiceActionInput", method + "Key", "LabKey")
            setting(key, "DataType", "Text")
            setting(key, "ReceiveIn", "Header")
            setting(key, "IsMandatory", True)
            if action["inputs"]:
                payload = create(method, "IRestServiceActionInput", method + "Payload", "Payload")
                setting(payload, "DataType", optional_text)
                setting(payload, "ReceiveIn", "Body")
            output = create(method, "IRestServiceActionOutput", method + "Output", "Result")
            setting(output, "DataType", action["outputs"][0]["type"])
            setting(output, "SendIn", "Body")
            authenticate = create(method, "IExecuteServerActionNode", method + "Auth", "AuthenticateLab")
            setting(authenticate, "Action", "IServerAction:LabAuthenticate")
            setting(authenticate + "/LabKey", "Value", "LabKey")
            execute = create(method, "IExecuteServerActionNode", method + "Execute", "ExecuteProbe")
            setting(execute, "Action", "IServerAction:" + name)
            if action["inputs"]:
                parameter = action["inputs"][0]
                setting(execute + "/" + parameter["name"], "Value", "Payload" if parameter["type"] == optional_text else "Payload.Value")
            node = create(method, "IAssignNode", method + "Assign", "SetResult")
            field = create(node, "IAssignment", method + "Field")
            setting(field, "Variable", "Result")
            setting(field, "Value", "ExecuteProbe." + action["outputs"][0]["name"])
            link(method + "/#IStartNode", authenticate)
            link(authenticate, execute)
            link(execute, node)
            link(node, method + "/#IEndNode")
            ops.append({"op": "layout", "target": method})
    job = {"description": "Authenticated transport for literal C# differential cases; fictional personal-lab user only",
        "base": "tests/fixtures/blank-service.oml", "expectValid": True, "ops": ops}
    (work / "transport.json").write_text(json.dumps(job, indent=2), encoding="utf-8")
    print(json.dumps({"job": str(work / "transport.json"), "cases": len(cases), "ops": len(ops)}))


def run(work: pathlib.Path, origin: str, source: pathlib.Path | None = None) -> int:
    url = urllib.parse.urlsplit(origin)
    if url.scheme != "https" or url.netloc != HOST or url.path not in ("", "/") or url.query or url.fragment:
        raise ValueError("Only the explicitly authorized personal laboratory origin is accepted")
    publication = json.loads((work / "confirmed-publish.json").read_text(encoding="utf-8"))
    if publication.get("Completed") is not True or publication.get("HasErrors") is not False or not publication.get("VersionId"):
        raise ValueError("A completed, error-free server publication is required before runtime tests")
    key = json.loads((work / "secrets.json").read_text(encoding="utf-8"))["key"]
    cases = json.loads((work / "cases.json").read_text(encoding="utf-8"))
    run_dir = work / "runs" / (time.strftime("%Y%m%d-%H%M%S") + "-" + secrets.token_hex(4))
    run_dir.mkdir(parents=True)
    shutil.copyfile(source or work / "RuntimeSource.json", run_dir / "RuntimeSource.json")
    for name in ["cases.json", "transport.json", "confirmed-publish.json", "snapshot-for-publish.json", "source-check.json"]:
        if (work / name).exists():
            shutil.copyfile(work / name, run_dir / name)
    results = []
    for case, token in [(cases[0], "invalid-key")] + [(case, key) for case in cases]:
        request = urllib.request.Request(origin.rstrip("/") + f"/{MODULE}/rest/CSharpLab/" + case["case"],
            data=b"", headers={"LabKey": token}, method="POST")
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                status, body = response.status, response.read().decode("utf-8")
        except urllib.error.HTTPError as error:
            status, body = error.code, error.read().decode("utf-8")
        anonymous = token != key
        try:
            result = json.loads(body)
        except json.JSONDecodeError:
            result = body
        passed = status >= 400 if anonymous else status == 200 and (result is True or result == {"Passed": True})
        results.append({"case": case["case"], "method": case["method"], "invalidKey": anonymous,
            "status": status, "result": result, "passed": passed})
        (work / "execution.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
        (run_dir / "execution.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
        print(json.dumps({k: v for k, v in results[-1].items() if k != "result"}), flush=True)
    # HTTP-provided Unicode is independent of the compiler's constant encoding. This catches a
    # malformed constant codec that might otherwise change both a case argument and its expectation.
    fixture = pathlib.Path(__file__).resolve().parents[3] / "tests/csharp/TextSemantics.cases.json"
    if any(case["method"].startswith("TextRules.") for case in cases):
        probes = json.loads(fixture.read_text(encoding="utf-8")) + [
            {"method": "Echo", "arguments": [value], "expected": value} for value in ["\r", "\r\n", "\u0000", "\u200b"]] + [
            {"method": "CarriageReturn", "arguments": [], "expected": "\r"}]
        for index, test in enumerate(probes):
            value = test["arguments"][0] if test["arguments"] else None
            payload = json.dumps({"HasValue": value is not None, "Value": value or ""}).encode("utf-8")
            request = urllib.request.Request(origin.rstrip("/") + f"/{MODULE}/rest/CSharpLab/Probe" + test["method"],
                data=payload, headers={"LabKey": key, "Content-Type": "application/json"}, method="POST")
            try:
                with urllib.request.urlopen(request, timeout=60) as response:
                    status, body = response.status, response.read().decode("utf-8")
            except urllib.error.HTTPError as error:
                status, body = error.code, error.read().decode("utf-8")
            try:
                result = json.loads(body)
            except json.JSONDecodeError:
                result = body
            if isinstance(result, dict) and set(result) == {"Result"}:
                result = result["Result"]
            passed = status == 200 and type(result) == type(test["expected"]) and result == test["expected"]
            results.append({"case": "Wire" + str(index), "method": test["method"], "input": value,
                "expected": test["expected"], "status": status, "result": result, "passed": passed})
            (work / "execution.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
            (run_dir / "execution.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
            print(json.dumps({"case": results[-1]["case"], "method": test["method"], "status": status, "passed": passed}), flush=True)
    return 0 if all(result["passed"] for result in results) else 1


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["build", "run"])
    parser.add_argument("--work", type=pathlib.Path, required=True)
    parser.add_argument("--origin", default="https://" + HOST)
    parser.add_argument("--source", type=pathlib.Path, help="Exact delivered C# bundle to freeze as runtime evidence")
    parser.add_argument("--replace", action="store_true", help="rebuild the existing lab HTTP transport; never deletes business actions")
    args = parser.parse_args()
    if args.mode == "build":
        build(args.work, args.replace)
    else:
        raise SystemExit(run(args.work, args.origin, args.source))
