using System.Globalization;
using System.Security.Cryptography;
using System.Text;

namespace Anvil.Core.ExternalLibraries;

/// <summary>
/// The C# project of an External Library, generated from its spec: the same spec gives the same bytes (LF line ends,
/// fixed order, no time or machine data). net10.0 and the OutSystems.ExternalLibraries.SDK version are constants here,
/// never inputs: every library SSAM builds targets what ODC runs. Layout as the ODC templates: an interface
/// I&lt;Name&gt; marked [OSInterface] with one [OSAction] method per action ([OSParameter] on each input), the class
/// &lt;Name&gt; that implements it with the spec bodies, and the [OSStructure] structures. A body uses the declared names
/// (D8): inputs are the method parameters; one output is a local returned at the end; several outputs are out parameters.
/// </summary>
public static class ExternalLibraryProject
{
    public const string SdkPackage = "OutSystems.ExternalLibraries.SDK";
    /// <summary>The SDK version the GitSSAM flow proved; a new version enters here, once, after a live proof.</summary>
    public const string SdkVersion = "1.5.0";
    public const string TargetFramework = "net10.0";
    public const string Runtime = "linux-x64";
    private const string Header = "// Generated by SSAM from the external library spec. Change the spec, not this file.";

    /// <summary>Where each piece of the spec landed: file and 1-based line range (bodies: the body lines only).</summary>
    public sealed record Span(string Kind, int Index, string File, int FirstLine, int LastLine);
    public sealed record Project(string Name, string ProjectFile, IReadOnlyDictionary<string, string> Files, IReadOnlyList<Span> Spans)
    {
        public string Sha256(string file) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(Files[file]))).ToLowerInvariant();
    }

    public static Project Generate(ExternalLibrarySpec spec)
    {
        var spans = new List<Span>();
        var usings = new[] { SdkPackage }.Concat(spec.Usings.Where(u => u != SdkPackage)).ToArray();
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal)
        {
            [spec.Name + ".csproj"] = Csproj(spec),
            ["I" + spec.Name + ".cs"] = Interface(spec, usings, spans),
            [spec.Name + ".cs"] = Implementation(spec, usings, spans),
            ["Structures.cs"] = Structures(spec, usings, spans),
        };
        return new Project(spec.Name, spec.Name + ".csproj", files, spans);
    }

    /// <summary>Writes the project into a new or empty folder; never over existing files.</summary>
    public static void Write(Project project, string directory)
    {
        Directory.CreateDirectory(directory);
        if (Directory.EnumerateFileSystemEntries(directory).Any()) throw new IOException("The project folder must be new or empty: " + directory);
        foreach (var (file, text) in project.Files)
        {
            using var stream = new FileStream(Path.Combine(directory, file), FileMode.CreateNew, FileAccess.Write);
            var bytes = new UTF8Encoding(false).GetBytes(text);
            stream.Write(bytes);
        }
    }

    private static string Csproj(ExternalLibrarySpec spec)
    {
        var b = new StringBuilder();
        b.Append("<Project Sdk=\"Microsoft.NET.Sdk\">\n\n");
        b.Append("  <PropertyGroup>\n");
        b.Append("    <TargetFramework>").Append(TargetFramework).Append("</TargetFramework>\n");
        b.Append("    <AssemblyName>").Append(Xml(spec.Name)).Append("</AssemblyName>\n");
        b.Append("    <RootNamespace>").Append(Xml(spec.Namespace)).Append("</RootNamespace>\n");
        b.Append("    <ImplicitUsings>enable</ImplicitUsings>\n");
        b.Append("    <Nullable>disable</Nullable>\n");
        b.Append("    <Deterministic>true</Deterministic>\n");
        b.Append("    <ContinuousIntegrationBuild>true</ContinuousIntegrationBuild>\n");
        // The folder the build runs in never reaches the assembly or its symbols: the same spec, the same zip, anywhere.
        b.Append("    <PathMap>$(MSBuildProjectDirectory)=/_/</PathMap>\n");
        b.Append("    <GenerateDocumentationFile>false</GenerateDocumentationFile>\n");
        b.Append("    <SatelliteResourceLanguages>en</SatelliteResourceLanguages>\n");
        b.Append("  </PropertyGroup>\n\n");
        b.Append("  <ItemGroup>\n");
        b.Append("    <PackageReference Include=\"").Append(SdkPackage).Append("\" Version=\"").Append(SdkVersion).Append("\" />\n");
        foreach (var p in spec.Packages.OrderBy(p => p.Name, StringComparer.OrdinalIgnoreCase))
            b.Append("    <PackageReference Include=\"").Append(Xml(p.Name)).Append("\" Version=\"").Append(Xml(p.Version)).Append("\" />\n");
        b.Append("  </ItemGroup>\n\n");
        b.Append("</Project>\n");
        return b.ToString();
    }

    private static string Interface(ExternalLibrarySpec spec, string[] usings, List<Span> spans)
    {
        var file = "I" + spec.Name + ".cs";
        var lines = Preamble(spec, usings);
        lines.Add(Attribute("OSInterface", spec.Description is { Length: > 0 } d ? ["Description = " + Literal(d)] : []));
        lines.Add("public interface I" + spec.Name);
        lines.Add("{");
        for (var i = 0; i < spec.Actions.Count; i++)
        {
            var action = spec.Actions[i];
            var first = lines.Count + 1;
            if (i > 0) lines.Add("");
            lines.Add("    " + Attribute("OSAction", ActionArguments(action)));
            var parameters = action.Inputs.Select(p => Attribute("OSParameter", ParameterArguments(p)) + " " + CsType(p.Type) + " " + p.Name + DefaultValue(p))
                .Concat(action.Outputs.Count > 1 ? action.Outputs.Select(p => Attribute("OSParameter", ParameterArguments(p)) + " out " + CsType(p.Type) + " " + p.Name) : []);
            lines.Add("    " + ReturnType(action) + " " + action.Name + "(" + string.Join(", ", parameters) + ");");
            spans.Add(new Span("action", i, file, first, lines.Count));
        }
        lines.Add("}");
        return Join(lines);
    }

    private static string Implementation(ExternalLibrarySpec spec, string[] usings, List<Span> spans)
    {
        var file = spec.Name + ".cs";
        var lines = Preamble(spec, usings);
        lines.Add("public class " + spec.Name + " : I" + spec.Name);
        lines.Add("{");
        for (var i = 0; i < spec.Actions.Count; i++)
        {
            var action = spec.Actions[i];
            if (i > 0) lines.Add("");
            var methodFirst = lines.Count + 1;
            var parameters = action.Inputs.Select(p => CsType(p.Type) + " " + p.Name)
                .Concat(action.Outputs.Count > 1 ? action.Outputs.Select(p => "out " + CsType(p.Type) + " " + p.Name) : []);
            lines.Add("    public " + ReturnType(action) + " " + action.Name + "(" + string.Join(", ", parameters) + ")");
            lines.Add("    {");
            foreach (var output in action.Outputs)
                lines.Add(action.Outputs.Count == 1 ? "        " + CsType(output.Type) + " " + output.Name + " = " + Initial(output.Type) + ";"
                    : "        " + output.Name + " = " + Initial(output.Type) + ";");
            var bodyFirst = lines.Count + 1;
            foreach (var line in action.Body.Replace("\r\n", "\n").Replace('\r', '\n').Trim('\n').Split('\n'))
                lines.Add(line.Trim().Length == 0 ? "" : "        " + line.TrimEnd());
            spans.Add(new Span("body", i, file, bodyFirst, lines.Count));
            if (action.Outputs.Count == 1) lines.Add("        return " + action.Outputs[0].Name + ";");
            lines.Add("    }");
            spans.Add(new Span("action", i, file, methodFirst, lines.Count));
        }
        lines.Add("}");
        return Join(lines);
    }

    private static string Structures(ExternalLibrarySpec spec, string[] usings, List<Span> spans)
    {
        var file = "Structures.cs";
        var lines = Preamble(spec, usings);
        if (spec.Structures.Count == 0) lines.Add("// No structures declared.");
        for (var i = 0; i < spec.Structures.Count; i++)
        {
            var s = spec.Structures[i];
            if (i > 0) lines.Add("");
            var first = lines.Count + 1;
            lines.Add(Attribute("OSStructure", s.Description is { Length: > 0 } d ? ["Description = " + Literal(d)] : []));
            lines.Add("public struct " + s.Name);
            lines.Add("{");
            for (var j = 0; j < s.Attributes.Count; j++)
            {
                var a = s.Attributes[j];
                if (j > 0) lines.Add("");
                lines.Add("    " + Attribute("OSStructureField", FieldArguments(a)));
                lines.Add("    public " + CsType(a.Type) + " " + a.Name + " { get; set; }");
            }
            lines.Add("}");
            spans.Add(new Span("structure", i, file, first, lines.Count));
        }
        return Join(lines);
    }

    private static List<string> Preamble(ExternalLibrarySpec spec, string[] usings)
    {
        var lines = new List<string> { Header };
        lines.AddRange(usings.Select(u => "using " + u + ";"));
        lines.Add("");
        lines.Add("namespace " + spec.Namespace + ";");
        lines.Add("");
        return lines;
    }
    private static string Join(List<string> lines) => string.Join("\n", lines) + "\n";

    private static IEnumerable<string> ActionArguments(ExternalLibraryAction action)
    {
        if (action.Description is { Length: > 0 } d) yield return "Description = " + Literal(d);
        if (action.Outputs.Count != 1) yield break;
        var output = action.Outputs[0];
        yield return "ReturnName = " + Literal(output.Name);
        if (output.Description is { Length: > 0 } od) yield return "ReturnDescription = " + Literal(od);
        if (OsDataType(output.Type) is { } t) yield return "ReturnType = OSDataType." + t;
    }
    private static IEnumerable<string> ParameterArguments(ExternalLibraryParameter p)
    {
        if (p.Description is { Length: > 0 } d) yield return "Description = " + Literal(d);
        if (OsDataType(p.Type) is { } t) yield return "DataType = OSDataType." + t;
    }
    private static IEnumerable<string> FieldArguments(ExternalLibraryAttribute a)
    {
        if (a.Description is { Length: > 0 } d) yield return "Description = " + Literal(d);
        if (OsDataType(a.Type) is { } t) yield return "DataType = OSDataType." + t;
        if (a.Mandatory) yield return "IsMandatory = true";
        if (a.Length is > 0) yield return "Length = " + a.Length.Value.ToString(CultureInfo.InvariantCulture);
        if (a.Decimals is > 0) yield return "Decimals = " + a.Decimals.Value.ToString(CultureInfo.InvariantCulture);
        if (a.Default is { Length: > 0 } dv) yield return "DefaultValue = " + Literal(dv);
    }
    private static string Attribute(string name, IEnumerable<string> arguments)
    {
        var list = arguments.ToArray();
        return list.Length == 0 ? "[" + name + "]" : "[" + name + "(" + string.Join(", ", list) + ")]";
    }
    private static string ReturnType(ExternalLibraryAction action) => action.Outputs.Count == 1 ? CsType(action.Outputs[0].Type) : "void";
    private static string DefaultValue(ExternalLibraryParameter p)
    {
        if (p.Default == null) return "";
        return " = " + (CsType(p.Type) is "string" ? Literal(p.Default) : p.Default);
    }

    /// <summary>OSDataType member of a primitive (lists and structures take their type from the C# declaration).</summary>
    public static string? OsDataType(string canonical) => ExternalLibrarySpec.ListItem(canonical) == null
        && ExternalLibrarySpec.Primitives.Values.Contains(canonical) ? canonical : null;
    public static string CsType(string canonical)
    {
        if (ExternalLibrarySpec.ListItem(canonical) is { } item) return "List<" + CsType(item) + ">";
        return canonical switch
        {
            "Text" or "Email" or "PhoneNumber" => "string",
            "Integer" => "int",
            "LongInteger" => "long",
            "Decimal" or "Currency" => "decimal",
            "Boolean" => "bool",
            "Date" or "DateTime" => "DateTime",
            "Time" => "TimeSpan",
            "BinaryData" => "byte[]",
            _ => canonical,
        };
    }
    private static string Initial(string canonical)
    {
        if (ExternalLibrarySpec.ListItem(canonical) != null) return "new " + CsType(canonical) + "()";
        return CsType(canonical) switch { "string" => "\"\"", "byte[]" => "Array.Empty<byte>()", _ => "default" };
    }
    /// <summary>A C# regular string literal; non-ASCII characters are escaped so the bytes never depend on an encoding.</summary>
    public static string Literal(string value)
    {
        var b = new StringBuilder("\"");
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': b.Append("\\\""); break;
                case '\\': b.Append("\\\\"); break;
                case '\n': b.Append("\\n"); break;
                case '\r': b.Append("\\r"); break;
                case '\t': b.Append("\\t"); break;
                default:
                    if (c < 0x20 || c > 0x7e) b.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    else b.Append(c);
                    break;
            }
        }
        return b.Append('"').ToString();
    }
    private static string Xml(string value) => value.Replace("&", "&amp;").Replace("\"", "&quot;").Replace("<", "&lt;").Replace(">", "&gt;");
}
