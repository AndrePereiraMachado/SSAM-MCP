using System.Text.Json.Nodes;
using System.Xml.Linq;
using OutSystems.Model.Implementation;
using OutSystems.Model.Implementation.Oml;
using OutSystems.Model.Implementation.Oml.Signatures;
using ServiceStudio.Model;
using ServiceStudio.Model.Interfaces;

namespace Anvil.Core;

public sealed record SignatureFixture(NativeReferenceSnapshot Snapshot, JsonObject Report);

/// <summary>
/// OFFLINE EVIDENCE ONLY. Builds attested (FormatVersion 2) producer envelopes without a server, so the eSpace and
/// system import paths can be proven on local copies:
///   - FromProducerOml: the signature fragment a producer OML carries (not the server bytes; the server hash differs,
///     gaps/verify/sighash.log), Source "producer-oml";
///   - FromConsumers: each element of an existing consumer reference regenerated by the Studio's own signature
///     serializer (ESpace.GetSignatureForDebugPurposes) and checked against the FullSignatureHash the consumer stored
///     when it last refreshed from the server, Source "consumer-reconstruction".
/// The SignatureHash of these envelopes is computed locally and never equals a server hash, the environment defaults
/// to an invalid host, and NativeReferenceSnapshot.RequireDeliverable refuses both sources: they cannot be delivered.
/// </summary>
public static class SignatureFixtures
{
    public const string OfflineEnvironment = "offline.invalid";

    public static SignatureFixture FromProducerOml(string omlPath, IReadOnlyList<string> elements, string environment = OfflineEnvironment)
    {
        var bytes = File.ReadAllBytes(omlPath);
        var header = Oml.GetOmlHeader(bytes);
#pragma warning disable CS0612, CS0618
        using var oml = Oml.LoadWithoutUpgrades(bytes, "");
#pragma warning restore CS0612, CS0618
        var full = oml.GetSignature();
        // Only the public payload: the Studio's local bookkeeping (ServiceStudioData) is not part of a server signature.
        var signature = new XElement(full.Name, full.Attributes(), full.Elements().Where(e => e.Name != "ServiceStudioData"));
        var report = new JsonObject { ["source"] = NativeReferenceAttestation.ProducerOml, ["oml"] = Path.GetFullPath(omlPath),
            ["omlSha256"] = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(bytes)).ToLowerInvariant() };
        return Build(header.Key.ToString(), header.Name, OutSystems.Model.Enumerations.ReferenceKind.eSpace, header.ESpaceType.ToString(),
            signature, elements, environment, NativeReferenceAttestation.ProducerOml, false, report);
    }

    public static SignatureFixture FromConsumers(ModelHost host, IReadOnlyList<string> consumerOmls, string producerKey,
        IReadOnlyList<string> elements, bool isSystem, string environment = OfflineEnvironment)
    {
        var key = Keys.Parse(producerKey);
        var payload = new Dictionary<string, XElement>(StringComparer.Ordinal);
        string? name = null, moduleType = null; var kind = OutSystems.Model.Enumerations.ReferenceKind.eSpace;
        var sources = new JsonArray(); var conflicts = new JsonArray();
        foreach (var path in consumerOmls)
        {
            var espace = host.Load(path);
            try
            {
                var reference = espace.References.SingleOrDefault(r => r.ReferenceKey != null && r.ReferenceKey.Equals(key))
                    ?? throw new InvalidOperationException(Path.GetFileName(path) + " does not reference producer " + producerKey);
                name ??= reference.Name; moduleType ??= ModelHost.Prop(reference, "ModuleType")?.ToString();
                if (reference.ReferenceKind == OutSystems.MetaModel.Enumerations.ReferenceKind.Extension) kind = OutSystems.Model.Enumerations.ReferenceKind.Extension;
                int verified = 0;
                foreach (var element in reference.DirectChildren.OfType<ITopLevelReferenceElement>())
                {
                    var generated = espace.GetSignatureForDebugPurposes(element).First;
                    // The consumer stored the server element's hash on its last refresh: a regenerated element that
                    // does not reproduce it is not the producer's signature and is refused.
                    if (generated.FullSignatureHash != element.FullSignatureHash)
                        throw new InvalidOperationException($"{Path.GetFileName(path)}: regenerated {generated.FullSignature.Name.LocalName} "
                            + $"{generated.FullSignature.Attribute("OriginalName")?.Value} does not reproduce the stored signature hash");
                    var saved = generated.Save();
                    var originalKey = generated.OriginalKey.ToString();
                    if (payload.TryGetValue(originalKey, out var first))
                    {
                        if (!XNode.DeepEquals(first, saved)) conflicts.Add((JsonNode)(generated.FullSignature.Attribute("OriginalName")?.Value + " (" + Path.GetFileName(path) + ")"));
                    }
                    else payload.Add(originalKey, saved);
                    verified++;
                }
                sources.Add(new JsonObject { ["oml"] = Path.GetFullPath(path), ["elements"] = verified, ["referenceHash"] = reference.ReferenceHash.ToString() });
            }
            finally { ModelHost.Release(espace); }
        }
        var signature = new XElement("Signature", new XAttribute("CreatedByTool", "Unspecified"),
            new XAttribute("ElementsOrderVersion", ModelConstants.CurrentElementsOrderVersion.ToString()),
            // Reference children do not enumerate in a stable order across loads: order by key so the payload, and the
            // locally computed hash, are reproducible from the same consumers.
            new XElement("AnonymousTypesNames"), new XElement("ElementSignatures", payload.OrderBy(p => p.Key, StringComparer.Ordinal).Select(p => p.Value)));
        var report = new JsonObject { ["source"] = NativeReferenceAttestation.ConsumerReconstruction, ["consumers"] = sources,
            ["keptFirstOnConflict"] = conflicts, ["elementSignatures"] = payload.Count };
        return Build(key.ToString(), name!, kind, moduleType, signature, elements, environment, NativeReferenceAttestation.ConsumerReconstruction, isSystem, report);
    }

    private static SignatureFixture Build(string producerKey, string name, OutSystems.Model.Enumerations.ReferenceKind kind, string? moduleType,
        XElement signature, IReadOnlyList<string> requested, string environment, string source, bool isSystem, JsonObject report)
    {
        var binary = Oml.SerializeSignature(signature);
        var hash = OmlAttrParser.GetGuid(SignatureHasher.CalculateHash(signature));
        var resolution = NativeDependencyReader.ResolveServerSignature(producerKey, name, binary, requested);
        var snapshot = NativeReferenceSnapshot.Create(new NativeReferenceSnapshot {
            FormatVersion = NativeReferenceSnapshot.AttestedFormatVersion, Environment = environment, ModuleKey = Keys.ToStudio(producerKey),
            ApplicationKey = "", Name = name, ModuleKind = kind,
            ModuleType = Enum.TryParse<OutSystems.Model.Enumerations.SegmentationKind>(moduleType, true, out var type) ? type : default,
            SignatureHash = hash, SignatureBinary = binary, Elements = ProducerSignatureCapture.Envelope(resolution),
            Attestation = new NativeReferenceAttestation { Source = source, IsSystem = isSystem, CapturedAtUtc = DateTime.UtcNow.ToString("O"),
                Tool = "anvil signature-fixture" } });
        report["producer"] = name; report["key"] = snapshot.ModuleKey; report["signatureHash"] = hash.ToString();
        report["signatureBytes"] = binary.Length; report["environment"] = environment; report["deliverable"] = false;
        report["elements"] = new JsonArray(resolution.Elements.Select(e => (JsonNode)(e.Type + ":" + e.Name + " = " + e.OriginalKey)).ToArray());
        report["closure"] = new JsonArray(resolution.Closure.Select(e => (JsonNode)(e.Type + ":" + e.Name + " = " + e.OriginalKey)).ToArray());
        report["foreignDependencies"] = new JsonArray(resolution.Foreign.Select(f => (JsonNode)f).ToArray());
        return new(snapshot, report);
    }
}
