using System.Text.Json.Nodes;
using ServiceStudio.Model;
using OutSystems.Model;

namespace Anvil.Core;

/// <summary>SS11 public constructors for entity indices, absent from Model API V1.
/// Used only inside the ordinary create transaction; no new verb or live mutation.</summary>
public static class EntityIndexes
{
    public static object Create(object parent, string? name, JsonObject? args, Func<string, object> resolve)
        => Create(parent, name, args, resolve, null);

    /// <summary><paramref name="noOp"/> (C21 of the atritos 3 package) hears an index equal to an existing explicit one (same
    /// attributes in the same order, same unique): nothing is created, the existing index is the result. A long name is
    /// truncated as the Studio truncates it (NameTruncation, 28 characters), never refused.</summary>
    public static object Create(object parent, string? name, JsonObject? args, Func<string, object> resolve, Action<string, string>? noOp)
    {
        if (parent is not Entity entity || entity.IsStaticEntity || entity.IsClientEntity)
            throw new InvalidOperationException("EntityIndex requires a local server entity");
        if (string.IsNullOrWhiteSpace(name)) throw new InvalidOperationException("EntityIndex requires name");
        if (args == null || args["attributes"] is not JsonArray refs || refs.Count == 0)
            throw new InvalidOperationException("EntityIndex requires args.attributes with at least one attribute reference");
        var unknown = args.Select(p => p.Key).Except(new[] { "attributes", "unique" }).ToArray();
        if (unknown.Length > 0) throw new InvalidOperationException("EntityIndex unknown args: " + string.Join(", ", unknown));
        var attributes = refs.Select(r => resolve(r!.GetValue<string>())).ToArray();
        if (attributes.Any(a => a is not EntityAttribute ea || !ReferenceEquals(ea.Parent, entity)))
            throw new InvalidOperationException("EntityIndex attributes must belong to its parent entity");
        if (attributes.Distinct().Count() != attributes.Length)
            throw new InvalidOperationException("EntityIndex cannot repeat an attribute");
        var unique = args["unique"]?.GetValue<bool>() ?? false;
        var existing = entity.EntityIndices.FirstOrDefault(i => i.IndexAttributes.Select(a => (object)a.Attribute).SequenceEqual(attributes));
        if (existing != null)
        {
            if (!existing.AutoGenerated)
            {
                // The same index again is what the module already has: a no-op, reported (indexNoOps), never a refusal.
                if (noOp != null && existing.Unique == unique) { noOp(name, existing.Name); return existing; }
                throw new InvalidOperationException($"EntityIndex duplicates an existing explicit index ('{existing.Name}', unique {existing.Unique}): "
                    + (existing.Unique == unique ? "it is the same index" : $"change it with set Unique {unique.ToString().ToLowerInvariant()} on EntityIndex:{existing.Name}"));
            }
            CheckName(entity, name, existing);
            existing.AutoGenerated = false;
            existing.SetName(name);
            existing.Unique = unique;
            return existing;
        }
        CheckName(entity, name);
        var index = new EntityIndex(entity, name) { Unique = unique };
        foreach (var attribute in attributes.Cast<EntityAttribute>()) _ = new EntityIndexAttribute(index, attribute);
        return index;
    }

    /// <summary>As duas plataformas truncam em silencio o nome de um indice a 28 caracteres (medido em 2026-09-23 no ODC
    /// 1.7.25.10778 e no Service Studio 11.55.87: 'IX_Contact_Email_Name_Status30' ficou 'IX_Contact_Email_Name_Status' e o
    /// contrato de dados recusou o job pela diferenca no Name). Recusa-se antes de escrever; o nome tambem tem de ser
    /// unico na entidade sem distincao de maiusculas.</summary>
    public const int MaxNameLength = NameTruncation.MaxLength;
    private static void CheckName(Entity entity, string name, EntityIndex? self = null)
    {
        if (name.Length > MaxNameLength)
            throw new InvalidOperationException($"EntityIndex name '{name}' has {name.Length} characters; the Studio truncates index names to {MaxNameLength} (it would become '{name[..MaxNameLength]}'); pick a shorter name");
        if (entity.EntityIndices.Any(i => !ReferenceEquals(i, self) && string.Equals(i.Name, name, StringComparison.OrdinalIgnoreCase)))
            throw new InvalidOperationException($"EntityIndex '{name}' already exists on {entity.Name}");
    }

    /// <summary>The names of the indexes of an entity (NameTruncation dedupes a truncated name against them).</summary>
    public static IEnumerable<string> Names(object parent) => parent is Entity entity ? entity.EntityIndices.Select(i => i.Name) : [];

    /// <summary>rename de um indice: o Model API do O11 nao expoe Name no EntityIndex (o `rename` generico recusava com
    /// "has no Name"), mas a classe nativa tem SetName -- o mesmo que o ODC faz pela propriedade. Mesmas regras de nome.</summary>
    public static JsonObject Rename(object value, string name)
    {
        if (value is not EntityIndex index) throw new InvalidOperationException("rename: not an EntityIndex");
        var from = index.Name;
        if (!string.Equals(from, name, StringComparison.Ordinal) && index.Parent is Entity entity) CheckName(entity, name);
        index.SetName(name);
        return new JsonObject { ["renamed"] = "EntityIndex '" + index.Name + "'", ["from"] = from, ["to"] = index.Name, ["consumers"] = 0, ["expressionsRewritten"] = 0,
            ["note"] = "an index has no consumers; its name is author text (nothing cites it)" };
    }

    /// <summary>O atributo de indice cujo Attribute tem esse nome: "EntityIndex:X/&lt;Atributo&gt;" nas duas faixas (no O11 os
    /// EntityIndexAttribute nao sao Children do indice).</summary>
    public static object? IndexAttribute(object value, string attributeName)
        => value is EntityIndex index ? index.IndexAttributes.FirstOrDefault(a => string.Equals(a.Attribute?.Name, attributeName, StringComparison.OrdinalIgnoreCase)) : null;

    /// <summary>The native children an object has outside Children (B3, atritos 3): an entity's indices, an index's attributes.</summary>
    public static IEnumerable<IObjectSignature> NativeChildren(object value) => value switch
    {
        Entity entity => entity.EntityIndices.Cast<IObjectSignature>(),
        EntityIndex index => index.IndexAttributes.Cast<IObjectSignature>(),
        _ => [],
    };

    public static IEnumerable<IObjectSignature> IncludeNative(IEnumerable<IObjectSignature> objects)
    {
        var all = objects.ToList();
        return all.Concat(all.OfType<Entity>().SelectMany(e => e.EntityIndices)
            .SelectMany(i => new IObjectSignature[] { i }.Concat(i.IndexAttributes.Cast<IObjectSignature>())))
            .Distinct();
    }

    public static string? TypeName(object value) => value switch
    {
        EntityIndex => "EntityIndex", EntityIndexAttribute => "EntityIndexAttribute", _ => null,
    };

    public static JsonObject? Read(object value) => value is EntityIndex index ? new JsonObject
    {
        ["type"] = "EntityIndex", ["name"] = index.Name, ["key"] = index.Key.ToString(),
        ["properties"] = new JsonObject { ["Unique"] = index.Unique, ["Entity"] = index.Parent.Name,
            ["Attributes"] = new JsonArray(index.IndexAttributes.Select(a => (JsonNode?)JsonValue.Create(a.Attribute?.Name)).ToArray()),
            // Os nomes sao para ler; o contrato de dados afere por CHAVE, senao renomear um atributo indexado
            // recusa a entrega com o indice correto no modelo (o rename segue por chave, a foto do nome nao).
            ["AttributeKeys"] = new JsonArray(index.IndexAttributes.Select(a => (JsonNode?)JsonValue.Create(((IObjectSignature?)a.Attribute)?.ObjectKey?.ToString())).ToArray()) },
    } : null;
}
