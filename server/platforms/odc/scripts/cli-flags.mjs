// The closed list of the flags SSAM's own command lines accept (round 7b of fix/no-internals, review no-internals-7 B2): the
// kernel CLIs (kernel/src), the lanes and the facade (platforms/odc, facade) and the scripts SSAM ships (kernel/scripts,
// scripts). A flag is a string literal of these sources that is exactly "--name" (a quote, then the flag, then a quote, a
// space, = or a separator). The licensee rule (facade/exposure.mjs) takes only these for a CLI flag: a CSS custom property
// of the customer (--brand-navy) or a word in a customer's expression ("--force") is never one.
// Usage: node platforms/odc/scripts/cli-flags.mjs [--write]   (prints the differences, or writes facade/cli-flags.mjs)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SKIP = new Set(['node_modules', 'bin', 'obj', '.local', 'tests', '.git', 'vendor']);
// exposure.mjs names CSS custom properties in its comments; cli-flags.mjs is the output
const OWN = /[\\/]facade[\\/](?:exposure|cli-flags)\.mjs$/;
const LITERAL = /["'`]--([a-z][a-z0-9]*(?:-[a-z0-9]+)*)(?=["'`\s=[\]|,.;:)])/g;
function files(dir, exts, out = []) {
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP.has(e.name)) files(p, exts, out); } else if (exts.some(x => e.name.endsWith(x))) out.push(p);
  }
  return out;
}
export function scanCliFlags(root) {
  const sources = [
    ...files(path.join(root, 'kernel', 'src'), ['.cs']),
    ...files(path.join(root, 'platforms', 'odc'), ['.cs', '.mjs']),
    ...files(path.join(root, 'facade'), ['.mjs']),
    ...files(path.join(root, 'kernel', 'scripts'), ['.py', '.mjs']),
    ...files(path.join(root, 'scripts'), ['.py', '.mjs']),
  ].filter(f => !OWN.test(f));
  const flags = new Set();
  for (const file of sources) for (const m of fs.readFileSync(file, 'utf8').matchAll(LITERAL)) flags.add(m[1]);
  return [...flags].sort();
}
const isMain = process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
  const list = scanCliFlags(root);
  const target = path.join(root, 'platforms', 'odc', 'facade', 'cli-flags.mjs');
  const lines = [];
  for (let i = 0, line = ''; i <= list.length; i++) {
    const item = i < list.length ? "'" + list[i] + "'," : null;
    if (item === null || (line + ' ' + item).length > 118) { if (line) lines.push('  ' + line); line = item ?? ''; } else line = line ? line + ' ' + item : item;
  }
  const text = '// Generated by platforms/odc/scripts/cli-flags.mjs --write (round 7b of fix/no-internals): the closed list of the flags\n'
    + "// SSAM's own command lines accept, from their sources. no-internals-text.test.mjs checks that it is current.\n"
    + 'export const CLI_FLAGS = new Set([\n' + lines.join('\n') + '\n]);\n';
  if (process.argv.includes('--write')) { fs.writeFileSync(target, text); console.log('wrote', target, list.length, 'flags'); }
  else {
    let current = []; try { current = [...(await import(pathToFileURL(target).href)).CLI_FLAGS].sort(); } catch { /* not written yet */ }
    const added = list.filter(f => !current.includes(f)), removed = current.filter(f => !list.includes(f));
    console.log(list.length, 'flags;', added.length, 'new:', added.join(' '), '|', removed.length, 'gone:', removed.join(' '));
  }
}
